# Characters that look like one of ours but are not in the table.
ALIASES = {
    "–": "-",   # en dash
    "’": "'",   # right single quote
    "‘": "'",
    "“": '"',
    "”": '"',
    "×": "x",
    " ": " ",   # non-breaking space
}

# Advance (in font units) for a glyph, from its widest set bit.
# A blank column is left after the widest ink so letters do not
# touch; the space character is a fixed 3 units.
_advance_cache = {}


def advance(ch):
    ch = ALIASES.get(ch, ch)
    got = _advance_cache.get(ch)
    if got is not None:
        return got
    rows = GLYPHS.get(ch)
    if rows is None:
        rows = GLYPHS["?"]
    if ch == " ":
        got = 3
    else:
        # widest set column index: bit 7 is column 0, bit 0 is column 7
        widest = 0
        for row in rows:
            col = 0
            r = row
            while r:
                if r & 0x80:
                    widest = max(widest, col + 1)
                r = (r << 1) & 0xFF
                col += 1
        got = widest + 1
    _advance_cache[ch] = got
    return got


def rows_for(ch, bold=False):
    """Row bytes for one character, bolded if asked."""
    ch = ALIASES.get(ch, ch)
    rows = GLYPHS.get(ch)
    if rows is None:
        rows = GLYPHS["?"]
    if bold:
        rows = tuple((r | (r >> 1)) & 0xFF for r in rows)
    return rows
